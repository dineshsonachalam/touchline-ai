#!/usr/bin/env python3
"""Deterministic, entirely synthetic football-realistic tracking data.
No positions, player paths, or events are copied from any real match.
"""
import json, math, random
from pathlib import Path

ROOT=Path(__file__).parent
OUT=ROOT/'public/data/match.json'
SEED=20261019
DT=.48
N=12084
DURATION=round((N-1)*DT,2)
# Nine authored, synthetic attacking situations, spread across a full match.
EVENTS=[(430,'home',2),(920,'away',3),(1430,'home',2),(1930,'away',2),(2510,'home',3),(3090,'away',2),(3670,'home',2),(4330,'away',3),(5070,'home',2)]
# positions for outfield players in normalized attack-left-to-right coordinates
FORMATION=[(33,10),(34,25),(34,43),(33,59),(49,13),(49,28),(49,45),(49,59),(64,24),(64,44)]

def clamp(x,a,b):return max(a,min(b,x))
def smoothstep(x):x=clamp(x,0,1);return x*x*(3-2*x)
def base(team,idx,phase,attack_right):
    if idx==0:return (5 if attack_right else 100,34)
    x,y=FORMATION[idx-1]
    if not attack_right:x=105-x
    # small coherent movement, never a real player's trajectory
    return (clamp(x+2.4*math.sin(phase*.7+idx*.81+(0 if team=='home' else 2)),3,102),
            clamp(y+2.1*math.sin(phase*.52+idx*.97),2,66))

def event_positions(team,carrier_y,attack_right):
    # Attacker with ball, an open forward teammate, and defenders away from lane.
    # A different, shorter lateral actual ball movement is scripted after the decision.
    home_attack=team=='home'
    attack=[];defend=[]
    for i in range(11):
        if i==0:attack.append((5,34));continue
        x,y=FORMATION[i-1]
        attack.append((x,y))
    attack[2]=(65,carrier_y)       # player 3, ball carrier
    attack[8]=(87,carrier_y-12)    # player 9, open forward option
    attack[9]=(77,carrier_y+13)
    attack[10]=(76,carrier_y-22)
    defend=[(100,34),(52,8),(57,19),(57,38),(60,59),(69,7),(70,48),(78,57),(91,50),(94,33),(77,34)]
    if not attack_right:
        attack=[(105-x,y) for x,y in attack]
        defend=[(105-x,y) for x,y in defend]
    return (attack,defend) if home_attack else (defend,attack)

def generate():
    frames=[]
    for k in range(N):
        t=round(k*DT,2)
        phase=t/28
        # HOME attacks right throughout; AWAY attacks left (simplified synthetic match).
        home=[base('home',i,phase,True) for i in range(11)]
        away=[base('away',i,phase+1.7,False) for i in range(11)]
        # Ordinary ball possession is synthetic and follows a team player.
        team='home' if int(t//46)%2==0 else 'away'
        carrier=2+int(t//13)%9
        poss=home if team=='home' else away
        ball=poss[carrier]
        for when,evt_team,kind in EVENTS:
            delta=t-when
            if abs(delta)>9:continue
            # Smoothly transition into a curated attack and out again.
            weight=smoothstep((delta+9)/5)*smoothstep((9-delta)/5)
            ey=29 if kind==2 else 40
            eh,ea=event_positions(evt_team,ey,evt_team=='home')
            home=[(round((1-weight)*p[0]+weight*q[0],2),round((1-weight)*p[1]+weight*q[1],2)) for p,q in zip(home,eh)]
            away=[(round((1-weight)*p[0]+weight*q[0],2),round((1-weight)*p[1]+weight*q[1],2)) for p,q in zip(away,ea)]
            if weight>.4:
                own=home if evt_team=='home' else away
                origin=own[2]
                # At the decision: ball stays at player 3. Afterwards it takes a
                # modest lateral path rather than the promising forward option.
                move=smoothstep(max(0,delta)/3.8)
                direction=1 if evt_team=='home' else -1
                ball=(round(clamp(origin[0]+direction*4*move,0,105),2),
                      round(clamp(origin[1]+7*move,0,68),2))
                break
        frames.append({'t':t,'home':home,'away':away,'ball':ball})
    payload={'kind':'synthetic_tracking','duration':DURATION,'frames':frames,
      'source':'Entirely synthetic football-realistic positions generated by generate_synthetic_match.py (seed 20261019). No real match data.',
      'disclaimer':'Illustrative synthetic match. Actual means recorded synthetic scenario, not real-world match events. AI alternatives are hypothetical.'}
    OUT.parent.mkdir(parents=True,exist_ok=True)
    OUT.write_text(json.dumps(payload,separators=(',',':')))
    print(f'Generated {len(frames)} entirely synthetic frames -> {OUT}')
if __name__=='__main__':generate()
